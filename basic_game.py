# Student Grade Calculator

print("===== STUDENT GRADE CALCULATOR =====")

name = input("Enter student name: ")

# Enter marks for 5 subjects
subjects = ["Python", "Mathematics", "English", "Science", "Computer Science"]
marks = []

for subject in subjects:
    mark = float(input(f"Enter marks in {subject} (out of 100): "))
    marks.append(mark)

# Calculate total and percentage
total = sum(marks)
percentage = total / len(subjects)

# Determine grade
if percentage >= 90:
    grade = "A+"
elif percentage >= 80:
    grade = "A"
elif percentage >= 70:
    grade = "B"
elif percentage >= 60:
    grade = "C"
elif percentage >= 50:
    grade = "D"
elif percentage >= 35:
    grade = "E"
else:
    grade = "F (Fail)"

# Display results
print("\n===== RESULT =====")
print("Student Name:", name)
print("Total Marks:", total, "/", len(subjects) * 100)
print("Percentage:", round(percentage, 2), "%")
print("Grade:", grade)

if percentage >= 35:
    print("Result: PASS")
else:
    print("Result: FAIL")